/**
 * Pre-render Quicksand Bold message layers for On Air (browser-safe runtime).
 * Run: npm run generate:on-air -w @pixopen/renderer
 */
import { createCanvas, GlobalFonts } from '@napi-rs/canvas';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
/** Static Bold — variable wght axis is ignored by @napi-rs/canvas. */
const FONT_PATH = join(ROOT, 'fonts/Quicksand/Quicksand-Bold.woff');
const OUT_PATH = join(ROOT, 'src/onAir/textLayers.ts');

const SIZE = 64;
const SUPER = 8; // 512 → 64 for soft Quicksand edges
const HI = SIZE * SUPER;
/** ~1px margin on the final 64×64 — fill the face. */
const PAD = 1 * SUPER;

/** @type {Record<string, string[]>} */
const MESSAGES = {
  'on-air': ['ON', 'AIR'],
  'in-a-meeting': ['IN A', 'MEETING'],
  recording: ['RECORDING'],
  'do-not-disturb': ['DO NOT', 'DISTURB'],
};

/** Optional per-preset scale after fit (1 = max size that fits). */
const SIZE_SCALE = {
  'on-air': 0.88,
};

GlobalFonts.registerFromPath(FONT_PATH, 'QuicksandBold');

function applyFont(ctx, fontPx) {
  ctx.font = `${fontPx}px QuicksandBold`;
  ctx.letterSpacing = '0px';
}

function measureBlock(ctx, lines, fontPx, lineGap) {
  applyFont(ctx, fontPx);
  let maxW = 0;
  for (const line of lines) {
    maxW = Math.max(maxW, ctx.measureText(line).width);
  }
  // Quicksand cap-height ~0.7em; pack lines tight for a filled sign face
  const lineH = fontPx * 0.78;
  const h = lines.length * lineH + Math.max(0, lines.length - 1) * lineGap;
  return { maxW, h, lineH };
}

function fitFont(ctx, lines) {
  const maxW = HI - PAD * 2;
  const maxH = HI - PAD * 2;
  let lo = 24;
  let hi = 360;
  let best = lo;
  while (lo <= hi) {
    const mid = Math.floor((lo + hi) / 2);
    const gap = Math.max(2, Math.round(mid * 0.04));
    const { maxW: w, h } = measureBlock(ctx, lines, mid, gap);
    if (w <= maxW && h <= maxH) {
      best = mid;
      lo = mid + 1;
    } else {
      hi = mid - 1;
    }
  }
  return best;
}

function renderAlpha(lines, scale = 1) {
  const canvas = createCanvas(HI, HI);
  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, HI, HI);
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  // Slight geometric precision for clean downsample
  ctx.imageSmoothingEnabled = true;

  const fontPx = Math.max(24, Math.round(fitFont(ctx, lines) * scale));
  const gap = Math.max(2, Math.round(fontPx * 0.04));
  const { h, lineH } = measureBlock(ctx, lines, fontPx, gap);
  applyFont(ctx, fontPx);

  let y = (HI - h) / 2 + lineH / 2;
  for (const line of lines) {
    // Stroke + fill punches Bold through the 64×64 downsample
    ctx.lineJoin = 'round';
    ctx.miterLimit = 2;
    // Light stroke only — enough weight for the downsample, not a hard outline
    ctx.lineWidth = Math.max(1, fontPx * 0.028);
    ctx.strokeStyle = '#ffffff';
    ctx.fillStyle = '#ffffff';
    ctx.strokeText(line, HI / 2, y);
    ctx.fillText(line, HI / 2, y);
    y += lineH + gap;
  }

  const { data } = ctx.getImageData(0, 0, HI, HI);
  const alpha = new Array(SIZE * SIZE);

  for (let ty = 0; ty < SIZE; ty++) {
    for (let tx = 0; tx < SIZE; tx++) {
      let sum = 0;
      let count = 0;
      const y0 = ty * SUPER;
      const x0 = tx * SUPER;
      for (let sy = 0; sy < SUPER; sy++) {
        for (let sx = 0; sx < SUPER; sx++) {
          const i = ((y0 + sy) * HI + (x0 + sx)) * 4;
          // Use max(alpha, luminance) — stroke/fill both contribute
          const a = data[i + 3];
          const lum = Math.max(data[i], data[i + 1], data[i + 2]);
          sum += Math.max(a, lum);
          count += 1;
        }
      }
      alpha[ty * SIZE + tx] = Math.min(255, Math.round(sum / count));
    }
  }

  return { alpha, fontPx };
}

const layers = {};
for (const [id, lines] of Object.entries(MESSAGES)) {
  const { alpha, fontPx } = renderAlpha(lines, SIZE_SCALE[id] ?? 1);
  layers[id] = alpha;
  const nz = alpha.filter((v) => v > 0).length;
  const strong = alpha.filter((v) => v > 180).length;
  console.log(`${id}: font=${fontPx}px lines=${JSON.stringify(lines)} coverage=${nz} strong=${strong}`);
}

const body = `/** Generated by scripts/generate-on-air-text.mjs — do not edit by hand. */
import type { OnAirMessage } from '@pixopen/core';

export const ON_AIR_TEXT_SIZE = ${SIZE} as const;

/** Soft Quicksand Bold alpha masks (0–255) for each preset, row-major 64×64. */
export const ON_AIR_TEXT_ALPHA: Record<OnAirMessage, number[]> = ${JSON.stringify(layers, null, 2)};
`;

writeFileSync(OUT_PATH, body);
console.log(`Wrote ${OUT_PATH}`);
